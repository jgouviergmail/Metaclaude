describe('resolve', () => {
  it('returns an empty context when nothing is registered', () => {
    expect(registry.resolve(wsA)).toEqual({ mcpServers: {}, agents: {} });
  });

  it('builds a stdio entry with the decrypted environment', () => {
    const server = registry.upsertMcpServer({
      workspaceId: wsA.id,
      name: 'files',
      transport: 'stdio',
      command: 'npx',
      args: ['-y', '@modelcontextprotocol/server-filesystem', '/data'],
      env: { API_KEY: 'sk-test-123', REGION: 'eu' },
    });

    const context = registry.resolve(wsA);
    expect(context.mcpServers).toEqual({
      files: {
        type: 'stdio',
        command: 'npx',
        args: ['-y', '@modelcontextprotocol/server-filesystem', '/data'],
        env: { API_KEY: 'sk-test-123', REGION: 'eu' },
      },
    });
    expect(server.envKeys.sort()).toEqual(['API_KEY', 'REGION']);
  });

  it('merges decrypted secrets over the static headers for an http server', () => {
    registry.upsertMcpServer({
      workspaceId: wsA.id,
      name: 'remote',
      transport: 'http',
      url: 'https://example.test/mcp',
      headers: { 'X-Trace': 'on', Authorization: 'placeholder' },
      env: { Authorization: 'Bearer real-token' },
    });

    expect(registry.resolve(wsA).mcpServers).toEqual({
      remote: {
        type: 'http',
        url: 'https://example.test/mcp',
        headers: { 'X-Trace': 'on', Authorization: 'Bearer real-token' },
      },
    });
  });

  it('keeps the sse transport tag', () => {
    registry.upsertMcpServer({
      workspaceId: null,
      name: 'events',
      transport: 'sse',
      url: 'https://example.test/sse',
    });
    expect(registry.resolve(wsA).mcpServers).toEqual({
      events: { type: 'sse', url: 'https://example.test/sse', headers: {} },
    });
  });

  it('skips disabled servers and servers belonging to another workspace', () => {
    registry.upsertMcpServer({
      workspaceId: wsA.id,
      name: 'enabled-server',
      transport: 'stdio',
      command: 'a',
    });
    registry.upsertMcpServer({
      workspaceId: wsA.id,
      name: 'disabled-server',
      transport: 'stdio',
      command: 'b',
      enabled: false,
    });
    registry.upsertMcpServer({
      workspaceId: wsB.id,
      name: 'foreign-server',
      transport: 'stdio',
      command: 'c',
    });
    registry.upsertMcpServer({
      workspaceId: null,
      name: 'global-server',
      transport: 'stdio',
      command: 'd',
    });

    expect(Object.keys(registry.resolve(wsA).mcpServers).sort()).toEqual([
      'enabled-server',
      'global-server',
    ]);
    expect(Object.keys(registry.resolve(wsB).mcpServers).sort()).toEqual([
      'foreign-server',
      'global-server',
    ]);
  });

  it('includes enabled agents keyed by name and skips disabled ones', () => {
    registry.upsertAgent({
      workspaceId: wsA.id,
      name: 'reviewer',
      description: 'Reviews diffs',
      prompt: 'You review code.',
      tools: ['Read', 'Grep'],
      model: 'sonnet',
    });
    registry.upsertAgent({
      workspaceId: wsA.id,
      name: 'minimal',
      description: 'No frills',
      prompt: 'Be brief.',
    });
    registry.upsertAgent({
      workspaceId: wsA.id,
      name: 'switched-off',
      description: 'Off',
      prompt: 'p',
      enabled: false,
    });
    registry.upsertAgent({
      workspaceId: wsB.id,
      name: 'foreign',
      description: 'Elsewhere',
      prompt: 'p',
    });

    const { agents } = registry.resolve(wsA);
    expect(Object.keys(agents).sort()).toEqual(['minimal', 'reviewer']);
    expect(agents.reviewer).toEqual({
      description: 'Reviews diffs',
      prompt: 'You review code.',
      tools: ['Read', 'Grep'],
      model: 'sonnet',
    });
    // Absent optional fields are omitted rather than set to null.
    expect(agents.minimal).toEqual({ description: 'No frills', prompt: 'Be brief.' });
    expect('tools' in (agents.minimal as object)).toBe(false);
    expect('model' in (agents.minimal as object)).toBe(false);
  });

  it('drops a secret the vault can no longer decrypt instead of failing the run', () => {
    const server = registry.upsertMcpServer({
      workspaceId: null,
      name: 'tampered',
      transport: 'stdio',
      command: 'x',
      env: { A: 'secret-a', B: 'secret-b' },
    });
    // Corrupt one ciphertext; GCM authentication will refuse to open it.
    db.prepare("UPDATE secrets SET ciphertext = ? WHERE scope = ? AND key = 'A'").run(
      Buffer.from('garbage'),
      `mcp:${server.id}`,
    );

    const entry = registry.resolve(wsA).mcpServers.tampered as { env: Record<string, string> };
    expect(entry.env).toEqual({ B: 'secret-b' });
  });
});
