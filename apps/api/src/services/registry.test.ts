describe('skills', () => {
  it('creates a skill and reads it back', () => {
    const skill = registry.upsertSkill({
      workspaceId: wsA.id,
      name: 'run-tests',
      description: 'How this repository runs its tests',
      body: 'Use `pnpm test`.',
    });

    expect(skill.id.startsWith('skl_')).toBe(true);
    expect(skill.workspaceId).toBe(wsA.id);
    expect(skill.name).toBe('run-tests');
    expect(skill.description).toBe('How this repository runs its tests');
    expect(skill.body).toBe('Use `pnpm test`.');
    expect(skill.enabled).toBe(true);
    expect(skill.autoGenerated).toBe(false);
    expect(skill.useCount).toBe(0);
    expect(registry.getSkill(skill.id)).toEqual(skill);
    expect(registry.getSkill('skl_nope')).toBeNull();
  });

  it('honours the enabled and autoGenerated flags', () => {
    const skill = registry.upsertSkill({
      workspaceId: null,
      name: 'learned',
      description: 'd',
      body: 'b',
      enabled: false,
      autoGenerated: true,
    });
    expect(skill.enabled).toBe(false);
    expect(skill.autoGenerated).toBe(true);
  });

  it('updates in place when an id is supplied', () => {
    const created = registry.upsertSkill({
      workspaceId: wsA.id,
      name: 'run-tests',
      description: 'old',
      body: 'old body',
    });

    const updated = registry.upsertSkill({
      id: created.id,
      workspaceId: wsA.id,
      name: 'run-the-tests',
      description: 'new',
      body: 'new body',
      enabled: false,
    });

    expect(updated.id).toBe(created.id);
    expect(updated.name).toBe('run-the-tests');
    expect(updated.description).toBe('new');
    expect(updated.body).toBe('new body');
    expect(updated.enabled).toBe(false);
    expect(updated.createdAt).toBe(created.createdAt);
    expect(registry.listSkills()).toHaveLength(1);
  });

  it('rejects a bad name', () => {
    for (const name of [
      'Uppercase',
      'has space',
      '-leading-dash',
      '_underscore',
      'trailing.dot',
      'ünïcode',
      '',
      'a'.repeat(65),
    ]) {
      expectRegistryError(
        () => registry.upsertSkill({ workspaceId: null, name, description: 'd', body: 'b' }),
        400,
        'lowercase letters',
      );
    }
    expect(registry.listSkills()).toHaveLength(0);
  });

  it('accepts the names it is documented to accept', () => {
    for (const name of ['a', '9', 'a-b-c', 'skill9', '0-start', 'a'.repeat(64)]) {
      expect(
        registry.upsertSkill({ workspaceId: null, name, description: 'd', body: 'b' }).name,
      ).toBe(name);
    }
  });

  it('rejects a duplicate name in the same scope with 409', () => {
    registry.upsertSkill({ workspaceId: null, name: 'dupe', description: 'd', body: 'b' });
    expectRegistryError(
      () => registry.upsertSkill({ workspaceId: null, name: 'dupe', description: 'd', body: 'b' }),
      409,
      'already exists',
    );

    registry.upsertSkill({ workspaceId: wsA.id, name: 'scoped', description: 'd', body: 'b' });
    expectRegistryError(
      () =>
        registry.upsertSkill({ workspaceId: wsA.id, name: 'scoped', description: 'd', body: 'b' }),
      409,
    );
  });

  it('allows the same name in different scopes', () => {
    registry.upsertSkill({ workspaceId: null, name: 'shared', description: 'g', body: 'b' });
    registry.upsertSkill({ workspaceId: wsA.id, name: 'shared', description: 'a', body: 'b' });
    registry.upsertSkill({ workspaceId: wsB.id, name: 'shared', description: 'b', body: 'b' });
    expect(registry.listSkills()).toHaveLength(3);
  });

  it('throws 404 when updating a skill that is not there', () => {
    expectRegistryError(
      () =>
        registry.upsertSkill({
          id: 'skl_nope',
          workspaceId: null,
          name: 'ghost',
          description: 'd',
          body: 'b',
        }),
      404,
    );
  });

  it('scopes listing: undefined is everything, null is global only, an id adds globals', () => {
    registry.upsertSkill({ workspaceId: null, name: 'global-one', description: 'd', body: 'b' });
    registry.upsertSkill({ workspaceId: wsA.id, name: 'alpha-one', description: 'd', body: 'b' });
    registry.upsertSkill({ workspaceId: wsB.id, name: 'beta-one', description: 'd', body: 'b' });

    expect(registry.listSkills().map((s) => s.name)).toEqual([
      'alpha-one',
      'beta-one',
      'global-one',
    ]);
    expect(registry.listSkills(null).map((s) => s.name)).toEqual(['global-one']);
    expect(registry.listSkills(wsA.id).map((s) => s.name)).toEqual(['alpha-one', 'global-one']);
    expect(registry.listSkills(wsB.id).map((s) => s.name)).toEqual(['beta-one', 'global-one']);
    expect(registry.listSkills('ws_nothing').map((s) => s.name)).toEqual(['global-one']);
  });

  it('deletes', () => {
    const skill = registry.upsertSkill({
      workspaceId: null,
      name: 'temporary',
      description: 'd',
      body: 'b',
    });
    expect(registry.deleteSkill(skill.id)).toBe(true);
    expect(registry.getSkill(skill.id)).toBeNull();
    expect(registry.deleteSkill(skill.id)).toBe(false);
    expect(registry.deleteSkill('skl_nope')).toBe(false);
  });

  /*
   * BUG (apps/api/src/services/registry.ts:174-183, `upsertSkill` update path):
   * the UPDATE is not wrapped in the `try/catch` that turns a UNIQUE violation
   * into a `RegistryError(409)`, so renaming a skill onto a name that already
   * exists in the same scope escapes as a raw `SqliteError`. The HTTP layer
   * then answers 500 instead of 409. `upsertAgent` (282-297) and
   * `upsertMcpServer` (417-436) have exactly the same gap.
   */
  it.skip('reports a rename collision as 409, like the insert path does', () => {
    registry.upsertSkill({ workspaceId: null, name: 'taken', description: 'd', body: 'b' });
    const other = registry.upsertSkill({
      workspaceId: null,
      name: 'free',
      description: 'd',
      body: 'b',
    });
    expectRegistryError(
      () =>
        registry.upsertSkill({
          id: other.id,
          workspaceId: null,
          name: 'taken',
          description: 'd',
          body: 'b',
        }),
      409,
    );
  });
});

