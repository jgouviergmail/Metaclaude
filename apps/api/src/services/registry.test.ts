import type { McpTransport, Workspace } from '@metaclaude/shared';
import { afterEach, beforeEach, describe, expect, it } from 'vitest';
import type { Db } from '../db/index.js';
import { migrate, openDatabase } from '../db/index.js';
import { defaultWorkspaceSettings, WorkspaceRepo } from '../kernel/repositories.js';
import { Vault } from '../security/vault.js';
import { Registry, RegistryError } from './registry.js';

let db: Db;
let vault: Vault;
let registry: Registry;
let wsA: Workspace;
let wsB: Workspace;

/** Assert that `fn` throws a `RegistryError` carrying `status`. */
function expectRegistryError(fn: () => unknown, status: number, fragment?: string): void {
  try {
    fn();
  } catch (error) {
    expect(error).toBeInstanceOf(RegistryError);
    expect((error as RegistryError).statusCode).toBe(status);
    if (fragment !== undefined) expect((error as Error).message).toContain(fragment);
    return;
  }
  expect.unreachable('expected a RegistryError');
}

beforeEach(() => {
  db = openDatabase({ path: ':memory:' });
  migrate(db);
  vault = new Vault(db, Buffer.alloc(32, 7));
  registry = new Registry(db, vault, () => {
    /* no-op logger */
  });

  const workspaces = new WorkspaceRepo(db);
  wsA = workspaces.create({
    name: 'Alpha',
    slug: 'alpha',
    description: '',
    path: '/tmp/alpha',
    color: '#6366f1',
    icon: 'folder',
    settings: defaultWorkspaceSettings(),
  });
  wsB = workspaces.create({
    name: 'Beta',
    slug: 'beta',
    description: '',
    path: '/tmp/beta',
    color: '#6366f1',
    icon: 'folder',
    settings: defaultWorkspaceSettings(),
  });
});

afterEach(() => {
  db.close();
});

