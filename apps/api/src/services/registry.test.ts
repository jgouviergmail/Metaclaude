describe('MCP servers — secret handling', () => {
  function create(env?: Record<string, string>) {
    return registry.upsertMcpServer({
      workspaceId: null,
      name: 'secretive',
      transport: 'stdio',
      command: 'npx',
      args: ['-y', 'server'],
      ...(env ? { env } : {}),
    });
  }

  /** Re-save the server the way an edit form would, with whatever env it shows. */
  function resave(
    id: string,
    patch: { env?: Record<string, string>; removeEnvKeys?: string[]; name?: string } = {},
  ) {
    return registry.upsertMcpServer({
      id,
      workspaceId: null,
      name: patch.name ?? 'secretive',
      transport: 'stdio',
      command: 'npx',
      args: ['-y', 'server'],
      ...(patch.env ? { env: patch.env } : {}),
      ...(patch.removeEnvKeys ? { removeEnvKeys: patch.removeEnvKeys } : {}),
    });
  }

  it('stores the value in the vault and never returns it on the record', () => {
    const server = create({ A: 'secret-a' });

    expect(server.envKeys).toEqual(['A']);
    expect(vault.get(`mcp:${server.id}`, 'A')).toBe('secret-a');
    // The record carries key names only.
    expect(JSON.stringify(server)).not.toContain('secret-a');
    expect(Object.keys(server)).not.toContain('env');
    // …and nothing in the mcp_servers row leaks it either.
    const row = db
      .prepare<[string], Record<string, unknown>>('SELECT * FROM mcp_servers WHERE id = ?')
      .get(server.id)!;
    expect(JSON.stringify(row)).not.toContain('secret-a');
    expect(row.env_keys).toBe('["A"]');
  });

  it('keeps an existing secret when the form submits an empty env map', () => {
    const server = create({ A: 'secret-a' });
    const saved = resave(server.id, { env: {} });

    expect(saved.envKeys).toEqual(['A']);
    expect(vault.get(`mcp:${server.id}`, 'A')).toBe('secret-a');
    // …and the value is still what a run would actually receive.
    const entry = registry.resolve(wsA).mcpServers.secretive as { env: Record<string, string> };
    expect(entry.env).toEqual({ A: 'secret-a' });
  });

  it('keeps an existing secret when the form submits a blank value', () => {
    const server = create({ A: 'secret-a' });
    const saved = resave(server.id, { env: { A: '' } });

    expect(saved.envKeys).toEqual(['A']);
    expect(vault.get(`mcp:${server.id}`, 'A')).toBe('secret-a');
  });

  it('keeps existing secrets when env is omitted entirely', () => {
    const server = create({ A: 'secret-a' });
    const saved = resave(server.id, { name: 'renamed' });

    expect(saved.name).toBe('renamed');
    expect(saved.envKeys).toEqual(['A']);
    expect(vault.get(`mcp:${server.id}`, 'A')).toBe('secret-a');
  });

  it('merges a newly submitted secret alongside the existing ones', () => {
    const server = create({ A: 'secret-a' });
    const saved = resave(server.id, { env: { B: 'secret-b' } });

    expect(saved.envKeys.sort()).toEqual(['A', 'B']);
    expect(vault.get(`mcp:${server.id}`, 'A')).toBe('secret-a');
    expect(vault.get(`mcp:${server.id}`, 'B')).toBe('secret-b');
  });

  it('overwrites a secret when a new non-blank value is submitted for the same key', () => {
    const server = create({ A: 'secret-a' });
    const saved = resave(server.id, { env: { A: 'rotated' } });

    expect(saved.envKeys).toEqual(['A']);
    expect(vault.get(`mcp:${server.id}`, 'A')).toBe('rotated');
  });

  it('removes only the keys named in removeEnvKeys', () => {
    const server = create({ A: 'secret-a' });
    resave(server.id, { env: { B: 'secret-b' } });

    const saved = resave(server.id, { removeEnvKeys: ['A'] });

    expect(saved.envKeys).toEqual(['B']);
    expect(vault.get(`mcp:${server.id}`, 'A')).toBeNull();
    expect(vault.get(`mcp:${server.id}`, 'B')).toBe('secret-b');
    expect(vault.listKeys(`mcp:${server.id}`)).toEqual(['B']);
  });

  it('lets a key be removed and re-added in one save', () => {
    const server = create({ A: 'secret-a' });
    const saved = resave(server.id, { env: { A: 'fresh' }, removeEnvKeys: ['A'] });

    // The removal filters the key out of `env_keys`, but the submitted value is
    // still written to the vault, so the two must be read together.
    expect(saved.envKeys).toEqual([]);
    expect(vault.get(`mcp:${server.id}`, 'A')).toBe('fresh');
  });

  it('clears the whole vault scope when the server is deleted', () => {
    const server = create({ A: 'secret-a' });
    resave(server.id, { env: { B: 'secret-b', C: 'secret-c' } });
    expect(vault.listKeys(`mcp:${server.id}`)).toEqual(['A', 'B', 'C']);

    expect(registry.deleteMcpServer(server.id)).toBe(true);
    expect(vault.listKeys(`mcp:${server.id}`)).toEqual([]);
    expect(registry.getMcpServer(server.id)).toBeNull();
    expect(registry.deleteMcpServer(server.id)).toBe(false);
  });

  it('keeps one server’s secrets away from another’s', () => {
    const first = create({ A: 'secret-a' });
    const second = registry.upsertMcpServer({
      workspaceId: null,
      name: 'other',
      transport: 'stdio',
      command: 'npx',
      env: { A: 'different-a' },
    });

    expect(vault.get(`mcp:${first.id}`, 'A')).toBe('secret-a');
    expect(vault.get(`mcp:${second.id}`, 'A')).toBe('different-a');

    registry.deleteMcpServer(second.id);
    expect(vault.get(`mcp:${first.id}`, 'A')).toBe('secret-a');
  });

  /*
   * BUG (apps/api/src/services/registry.ts:417-471, `upsertMcpServer`):
   * when `input.id` names a server that does not exist, the UPDATE matches no
   * rows, no INSERT is attempted, and the method returns `this.getMcpServer(id)`
   * — i.e. `null` — cast to `McpServerRecord`. Callers get a `null` typed as a
   * record. Worse, the submitted secrets are still written to the vault under
   * `mcp:<unknown id>`, leaving credentials behind that nothing will ever clean
   * up (`deleteMcpServer` is the only thing that clears a scope, and there is no
   * row to delete). Skills and agents both raise a 404 in the same situation.
   */
  it.skip('throws 404 when updating an MCP server that is not there', () => {
    expectRegistryError(
      () =>
        registry.upsertMcpServer({
          id: 'mcp_nope',
          workspaceId: null,
          name: 'ghost',
          transport: 'stdio',
          command: 'x',
          env: { TOKEN: 'leaked' },
        }),
      404,
    );
    expect(vault.listKeys('mcp:mcp_nope')).toEqual([]);
  });
});

