describe('MCP servers — validation', () => {
  it('requires a command for stdio', () => {
    expectRegistryError(
      () => registry.upsertMcpServer({ workspaceId: null, name: 'local', transport: 'stdio' }),
      400,
      'needs a command',
    );
    expectRegistryError(
      () =>
        registry.upsertMcpServer({
          workspaceId: null,
          name: 'local',
          transport: 'stdio',
          command: '   ',
        }),
      400,
      'needs a command',
    );
    expectRegistryError(
      () =>
        registry.upsertMcpServer({
          workspaceId: null,
          name: 'local',
          transport: 'stdio',
          command: null,
        }),
      400,
    );
    expect(
      registry.upsertMcpServer({
        workspaceId: null,
        name: 'local',
        transport: 'stdio',
        command: 'npx',
        args: ['-y', 'some-server'],
      }).command,
    ).toBe('npx');
  });

  it('requires a URL for sse and http', () => {
    for (const transport of ['sse', 'http'] as McpTransport[]) {
      expectRegistryError(
        () => registry.upsertMcpServer({ workspaceId: null, name: `n-${transport}`, transport }),
        400,
        'needs a URL',
      );
      expectRegistryError(
        () =>
          registry.upsertMcpServer({
            workspaceId: null,
            name: `n-${transport}`,
            transport,
            url: '  ',
          }),
        400,
        'needs a URL',
      );
      expect(
        registry.upsertMcpServer({
          workspaceId: null,
          name: `n-${transport}`,
          transport,
          url: 'https://example.test/mcp',
        }).url,
      ).toBe('https://example.test/mcp');
    }
  });

  it('rejects a URL scheme that is not http or https', () => {
    for (const url of ['ftp://example.test/mcp', 'file:///etc/passwd', 'ws://example.test']) {
      expectRegistryError(
        () => registry.upsertMcpServer({ workspaceId: null, name: 'remote', transport: 'http', url }),
        400,
        'must use http or https',
      );
    }
  });

  it('rejects a malformed URL', () => {
    for (const url of ['not a url', 'http//missing-colon', '://nope']) {
      expectRegistryError(
        () => registry.upsertMcpServer({ workspaceId: null, name: 'remote', transport: 'http', url }),
        400,
        'not valid',
      );
    }
  });

  it('validates the URL even on a stdio server that carries one', () => {
    expectRegistryError(
      () =>
        registry.upsertMcpServer({
          workspaceId: null,
          name: 'local',
          transport: 'stdio',
          command: 'npx',
          url: 'ftp://example.test',
        }),
      400,
      'must use http or https',
    );
  });

  it('rejects a bad server name', () => {
    for (const name of ['has space', 'dot.name', 'slash/name', '', 'a'.repeat(65)]) {
      expectRegistryError(
        () =>
          registry.upsertMcpServer({ workspaceId: null, name, transport: 'stdio', command: 'x' }),
        400,
        'letters, digits, dash and underscore',
      );
    }
    // Upper case, underscores and dashes are all fine here (unlike skills).
    expect(
      registry.upsertMcpServer({
        workspaceId: null,
        name: 'My_Server-1',
        transport: 'stdio',
        command: 'x',
      }).name,
    ).toBe('My_Server-1');
  });

  it('rejects a duplicate name with 409', () => {
    registry.upsertMcpServer({ workspaceId: null, name: 'dupe', transport: 'stdio', command: 'x' });
    expectRegistryError(
      () =>
        registry.upsertMcpServer({
          workspaceId: null,
          name: 'dupe',
          transport: 'stdio',
          command: 'x',
        }),
      409,
      'already exists',
    );
  });
});

